"""Authenticated API v1 snapshots and commands on the service's owner loop."""

import asyncio
from dataclasses import asdict
import hmac
import json
import math
import os
import re
import time
import uuid

from aiohttp import web

from . import __version__

API_VERSION = 1
ACTIONS = {"set", "refresh", "add", "rename", "remove", "pair"}
MAX_BODY = 4096
FIRMWARE_FIELDS = {
    "preflight_supported",
    "board",
    "installed_version",
    "latest_version",
    "candidate_id",
    "update_available",
    "install_supported",
    "blocked_reason",
    "in_progress",
    "stage",
    "progress_percent",
    "transfer_percent",
    "request_id",
    "status",
    "error",
    "recovery",
    "rollback_supported",
    "release_notes",
    "release_url",
}
DIAGNOSTIC_FIELDS = {
    "rx_gaps",
    "invalid_rx",
    "ack_failures",
    "output_mode",
    "serial_baudrate",
    "host_version",
    "heartbeat_owner",
    "query_mode",
}
DIAGNOSTIC_GROUPS = {
    "firmware": {
        "running_version",
        "target_version",
        "update_available",
        "update_supported",
        "boot_version",
        "trial",
    },
    "query_timing": {
        "query_interval_seconds",
        "response_wait_seconds",
        "rounds",
        "deadline_seconds",
    },
}


def native_snapshot(service):
    """Select public state without MQTT settings, raw frames or browser tokens.

    @param service Service owned by the calling event loop.
    @return Detached full snapshot data for API v1 consumers.
    """
    diagnostics = {
        key: value
        for key, value in service.diagnostics.items()
        if key in DIAGNOSTIC_FIELDS
        and isinstance(value, (str, int, float, bool, type(None)))
    }
    for group, fields in DIAGNOSTIC_GROUPS.items():
        value = service.diagnostics.get(group)
        if isinstance(value, dict):
            diagnostics[group] = {
                key: item
                for key, item in value.items()
                if key in fields
                and isinstance(item, (str, int, float, bool, type(None)))
            }
    devices = []
    now = time.monotonic()
    for device in service.devices.values():
        state = service.states.get(device.id)
        public = None
        if state is not None:
            public = {
                key: state[key]
                for key in ("outputs", "last_seen", "rssi", "lqi")
                if key in state
            }
            if "state_bits" in state:
                public["bits"] = state["state_bits"]
        devices.append(
            dict(
                asdict(device),
                state=public,
                availability=(
                    "online"
                    if service.ready
                    and now - service.seen.get(device.id, -1e9)
                    < service.config.offline_after
                    else "offline"
                ),
            )
        )
    # Results are generated by Service, not arbitrary request payloads. Select
    # their public fields so future transport/firmware metadata cannot leak.
    result_fields = {
        "request_id",
        "status",
        "action",
        "device",
        "updated",
        "error",
        "state",
        "mask",
        "value",
        "attempts",
        "counter",
        "candidate_id",
        "stage",
        "recovery",
    }
    results = [
        {k: v for k, v in result.items() if k in result_fields}
        for result in service.store.recent_results()
    ]
    discoveries = []
    for item in service.discovery_snapshot():
        discovery = {
            k: v
            for k, v in item.items()
            if k in {"device", "suffix", "configured", "rssi", "lqi", "last_seen"}
        }
        profile = item.get("profile")
        if isinstance(profile, dict):
            discovery["profile"] = {
                key: value
                for key, value in profile.items()
                if key
                in {
                    "experimental",
                    "status",
                    "outputs",
                    "suffix",
                    "reason",
                    "expires_at",
                    "token",
                }
                and isinstance(value, (str, int, float, bool, type(None)))
            }
        discoveries.append(discovery)
    data = dict(
        gateway=service.config.gateway,
        tag=service.config.tag,
        ready=service.ready,
        controls_enabled=service.config.output_mode != "disabled",
        simulated=service.simulated,
        diagnostics=diagnostics,
        pairing=service.pairing_summary(),
        devices=devices,
        discoveries=discoveries,
        results=results,
    )
    firmware_snapshot = getattr(service, "firmware_update_snapshot", None)
    firmware = firmware_snapshot() if firmware_snapshot else None
    if isinstance(firmware, dict):
        data["firmware_update"] = {
            key: value
            for key, value in firmware.items()
            if key in FIRMWARE_FIELDS
            and isinstance(value, (str, int, float, bool, type(None)))
        }
        if "transfer_percent" in firmware:
            percent = firmware["transfer_percent"]
            data["firmware_update"]["transfer_percent"] = (
                percent
                if type(percent) in (int, float)
                and 0 <= percent <= 100
                and math.isfinite(percent)
                else None
            )
        if firmware.get("in_progress") or firmware.get("recovery"):
            data["controls_enabled"] = False
    return json.loads(json.dumps(data))


class NativeAPI:
    """Bounded full-snapshot delivery with no network waits on the radio path."""

    def __init__(
        self,
        service,
        *,
        token,
        host="127.0.0.1",
        port=8090,
        queue_size=4,
        max_clients=32,
        send_timeout=5,
    ):
        """Prepare an authenticated listener and its in-process event epoch.

        @param service Owner-loop service and durable command authority.
        @param token Required bearer secret, supplied outside configuration files.
        @param host Listening address.
        @param port Listening port; zero is available to isolated tests.
        @param queue_size Maximum queued full snapshots per WebSocket client.
        @param max_clients Maximum simultaneous event subscribers.
        @param send_timeout Maximum seconds to wait for a client write.
        """
        if (
            not isinstance(token, str)
            or not token
            or not token.isascii()
            or any(c.isspace() for c in token)
        ):
            raise ValueError("API token must be nonempty ASCII without whitespace")
        if queue_size < 1 or max_clients < 1 or send_timeout <= 0:
            raise ValueError("API delivery limits must be positive")
        self.service, self.host, self.port = service, host, port
        self.credential = ("Bearer " + token).encode("ascii")
        self.epoch = uuid.uuid4().hex
        self.sequence = -1
        self.data = self.encoded = None
        self.clients = {}
        self.connecting = 0
        self.closers = set()
        self.queue_size, self.max_clients = queue_size, max_clients
        self.send_timeout = send_timeout
        self.runner = self.site = self.loop = None
        self.scheduled = self.timer = None
        self.closed = False

    @web.middleware
    async def authenticate(self, request, handler):
        """Require one bearer header on every route, including WebSocket upgrades.

        @param request Incoming HTTP request.
        @param handler Authenticated route handler.
        @return A no-store response or a generic authentication rejection.
        """
        headers = request.headers.getall("Authorization", [])
        if len(headers) != 1 or not hmac.compare_digest(
            headers[0].encode(), self.credential
        ):
            return web.json_response(
                {"error": "Unauthorized"},
                status=401,
                headers={"WWW-Authenticate": "Bearer", "Cache-Control": "no-store"},
            )
        if request.query_string and request.path != "/api/v1/firmware/preflight":
            return web.json_response(
                {"error": "Query parameters are not supported"}, status=400
            )
        response = await handler(request)
        if not response.prepared:
            response.headers["Cache-Control"] = "no-store"
        return response

    async def start(self):
        """Bind routes before the radio is opened and register owner-loop observation."""
        self.loop = asyncio.get_running_loop()
        app = web.Application(
            middlewares=[self.authenticate], client_max_size=MAX_BODY + 1
        )
        app.add_routes(
            [
                web.get("/health", self.health),
                web.get("/api/v1/info", self.info),
                web.get("/api/v1/snapshot", self.snapshot),
                web.get("/api/v1/firmware/preflight", self.preflight_firmware),
                web.get("/api/v1/events", self.events),
                web.post("/api/v1/commands", self.command),
                web.post("/api/v1/firmware/install", self.install_firmware),
                web.get("/api/v1/commands/{request_id}", self.result),
            ]
        )
        self.runner = web.AppRunner(app, access_log=None, shutdown_timeout=2)
        try:
            await self.runner.setup()
            self.site = web.TCPSite(self.runner, self.host, self.port)
            await self.site.start()
        except BaseException:
            await self.runner.cleanup()
            raise
        self.port = self.runner.addresses[0][1]
        self.service.change_listeners.add(self.changed)
        self.flush()
        self.tick()

    def changed(self):
        """Coalesce synchronous service mutations into one snapshot per loop iteration."""
        if not self.closed and self.scheduled is None:
            self.scheduled = self.loop.call_soon(self.flush)

    def tick(self):
        """Observe time-driven availability and pairing countdown even without MQTT."""
        if not self.closed:
            self.changed()
            self.timer = self.loop.call_later(1, self.tick)

    def flush(self):
        """Publish changed public state without awaiting any subscriber's socket."""
        if self.scheduled is not None:
            self.scheduled.cancel()
            self.scheduled = None
        if self.closed:
            return
        data = native_snapshot(self.service)
        if data == self.data:
            return
        self.data = data
        self.sequence += 1
        self.encoded = json.dumps(
            dict(
                type="snapshot",
                api_version=API_VERSION,
                epoch=self.epoch,
                sequence=self.sequence,
                data=data,
            )
        )
        for ws, queue in tuple(self.clients.items()):
            try:
                queue.put_nowait(self.encoded)
            except asyncio.QueueFull:
                del self.clients[ws]
                task = self.loop.create_task(self.drop(ws))
                self.closers.add(task)
                task.add_done_callback(self.closers.discard)

    async def drop(self, ws):
        """Close a stalled subscription without draining its outbound backlog.

        @param ws WebSocket whose consumer must reconnect for a fresh snapshot.
        """
        try:
            await asyncio.wait_for(
                ws.close(code=1013, message=b"Reconnect for snapshot", drain=False), 1
            )
        except (asyncio.TimeoutError, ConnectionError):
            pass

    async def info(self, request):
        """Return stable network identity and API compatibility metadata.

        @param request Authenticated HTTP request.
        @return API and host versions with network identity and simulation flag.
        """
        return web.json_response(
            dict(
                api_version=API_VERSION,
                gateway=self.service.config.gateway,
                tag=self.service.config.tag,
                host_version=__version__,
                simulated=self.service.simulated,
            )
        )

    async def health(self, request):
        """Report process liveness independently of radio or MQTT readiness.

        @param request Authenticated HTTP request.
        @return Successful liveness response even when the radio is offline.
        """
        return web.json_response(dict(status="ok", api_version=API_VERSION))

    async def snapshot(self, request):
        """Return the same authoritative envelope used by event subscribers.

        @param request Authenticated HTTP request.
        @return Current full snapshot with epoch and sequence.
        """
        self.flush()
        return web.Response(text=self.encoded, content_type="application/json")

    async def command(self, request):
        """Validate only the envelope and delegate command policy to Service.submit.

        @param request Authenticated bounded JSON command request.
        @return Service-level outcomes with HTTP 200, or an envelope error.
        """
        if request.content_type != "application/json":
            return web.json_response({"error": "Expected application/json"}, status=400)
        try:
            body = await asyncio.wait_for(request.read(), 5)
            if len(body) > MAX_BODY:
                raise web.HTTPRequestEntityTooLarge(
                    max_size=MAX_BODY, actual_size=len(body)
                )
            value = json.loads(body)
        except (ValueError, UnicodeError, RecursionError):
            return web.json_response({"error": "Invalid JSON"}, status=400)
        except asyncio.TimeoutError:
            raise web.HTTPRequestTimeout() from None
        if (
            not isinstance(value, dict)
            or set(value) != {"action", "payload"}
            or not isinstance(value["action"], str)
            or value["action"] not in ACTIONS
            or not isinstance(value["payload"], dict)
        ):
            return web.json_response({"error": "Invalid command envelope"}, status=400)
        return web.json_response(self.service.submit(value["action"], value["payload"]))

    async def preflight_firmware(self, request):
        """Expose read-only compatibility checks without accepting device or file paths.

        @param request Authenticated request with at most one candidate_id query value.
        @return Public advisory report, or HTTP 400 for an invalid selection.
        """
        if (
            set(request.query) - {"candidate_id"}
            or len(request.query.getall("candidate_id", [])) > 1
        ):
            return web.json_response({"error": "Invalid preflight query"}, status=400)
        try:
            value = self.service.firmware_preflight(request.query.get("candidate_id"))
        except ValueError:
            return web.json_response({"error": "Invalid candidate_id"}, status=400)
        return web.json_response(value)

    async def install_firmware(self, request):
        """Submit a catalog candidate without accepting paths or flashing in the API.

        @param request Authenticated bounded JSON request with two opaque IDs.
        @return Durable service result, or HTTP 400/413 for an invalid envelope.
        """
        if request.content_type != "application/json":
            return web.json_response({"error": "Expected application/json"}, status=400)
        try:
            body = await asyncio.wait_for(request.read(), 5)
            if len(body) > MAX_BODY:
                raise web.HTTPRequestEntityTooLarge(
                    max_size=MAX_BODY, actual_size=len(body)
                )
            value = json.loads(body)
        except (ValueError, UnicodeError, RecursionError):
            return web.json_response({"error": "Invalid JSON"}, status=400)
        except asyncio.TimeoutError:
            raise web.HTTPRequestTimeout() from None
        if (
            not isinstance(value, dict)
            or set(value) != {"request_id", "candidate_id"}
            or any(
                not isinstance(item, str)
                or not re.fullmatch(
                    (
                        r"[A-Za-z0-9_.:-]{1,128}"
                        if key == "request_id"
                        else r"[A-Za-z0-9_.:-]{1,256}"
                    ),
                    item,
                )
                for key, item in value.items()
            )
        ):
            return web.json_response({"error": "Invalid firmware envelope"}, status=400)
        return web.json_response(self.service.start_firmware_update(value))

    async def result(self, request):
        """Read an existing durable result without re-executing its command.

        @param request Authenticated request with a durable request identifier.
        @return Stored result or HTTP 404 when it is unknown.
        """
        request_id = request.match_info["request_id"]
        value = (
            self.service.command_result(request_id)
            if re.fullmatch(r"[A-Za-z0-9_.:-]{1,128}", request_id)
            else None
        )
        if value is None:
            return web.json_response({"error": "Unknown request ID"}, status=404)
        return web.json_response(value)

    async def send_events(self, ws, queue):
        """Bound socket writes independently of service processing.

        @param ws Subscriber WebSocket.
        @param queue Bounded queue of already encoded full snapshots.
        """
        while not ws.closed:
            value = await queue.get()
            await asyncio.wait_for(ws.send_str(value), self.send_timeout)

    async def receive_events(self, ws):
        """Consume close/ping frames; event sockets never accept command messages.

        @param ws Subscriber WebSocket.
        """
        async for _ in ws:
            await ws.close(code=1008, message=b"Use HTTP commands")
            break

    async def events(self, request):
        """Subscribe atomically with an initial snapshot, then stream bounded updates.

        @param request Authenticated WebSocket upgrade request.
        @return A WebSocket closed on disconnect, overload or shutdown.
        """
        if self.closed or len(self.clients) + self.connecting >= self.max_clients:
            raise web.HTTPServiceUnavailable(text="Too many event subscribers")
        ws = web.WebSocketResponse(heartbeat=20, max_msg_size=MAX_BODY, compress=False)
        self.connecting += 1
        try:
            await ws.prepare(request)
        finally:
            self.connecting -= 1
        if self.closed:
            await self.drop(ws)
            return ws
        # No await between the snapshot and registration. Any subsequent change
        # either coalesces into this initial snapshot or queues after it.
        self.flush()
        queue = asyncio.Queue(maxsize=self.queue_size)
        queue.put_nowait(self.encoded)
        self.clients[ws] = queue
        tasks = [
            asyncio.create_task(self.send_events(ws, queue)),
            asyncio.create_task(self.receive_events(ws)),
        ]
        try:
            done, _ = await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
            for task in done:
                task.result()
        except (asyncio.TimeoutError, ConnectionError):
            await self.drop(ws)
        finally:
            self.clients.pop(ws, None)
            for task in tasks:
                task.cancel()
            await asyncio.gather(*tasks, return_exceptions=True)
            await ws.close(drain=False)
        return ws

    async def close(self):
        """Remove observations and close subscribers before the service store closes."""
        self.closed = True
        self.service.change_listeners.discard(self.changed)
        for handle in (self.timer, self.scheduled):
            if handle is not None:
                handle.cancel()
        await asyncio.gather(*(self.drop(ws) for ws in tuple(self.clients)))
        await asyncio.gather(*tuple(self.closers))
        if self.runner:
            await self.runner.cleanup()


async def start_api(service, config):
    """Resolve the configured environment secret and start the machine API.

    @param service Owner-loop service.
    @param config Validated daemon configuration.
    @return Running API listener.
    """
    settings = config.api
    token = os.environ.get(settings["token_env"])
    if not token:
        raise ValueError("API token environment variable is not set")
    api = NativeAPI(service, token=token, host=settings["host"], port=settings["port"])
    await api.start()
    return api
